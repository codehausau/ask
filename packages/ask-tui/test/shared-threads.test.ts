import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { createServer } from "node:http";
import { mkdtemp, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import test from "node:test";
import { createClient, type OneShotRequest } from "@codehaus-au/ask/internal/chat";
import { readCurrentSession, readThread, sessionPath } from "@codehaus-au/ask/internal/session";
import { TuiChat } from "../src/chat.ts";

test("CLI/TUI handoff survives restart, context changes, and conflicts without additional completions", async t => {
  const cwd = await mkdtemp(path.join(tmpdir(), "ask-handoff-"));
  t.after(() => rm(cwd, { recursive: true, force: true }));
  const env = { ...process.env, ASK_STATE_DIR: path.join(cwd, "state") };
  const requests: OneShotRequest[] = [];
  const server = createServer(async (req, res) => {
    let raw = ""; for await (const chunk of req) raw += chunk;
    requests.push(JSON.parse(raw) as OneShotRequest);
    res.writeHead(200, { "content-type": "application/json" });
    res.end(JSON.stringify({ model: "stub", choices: [{ finish_reason: "stop", message: { content: `answer ${requests.length}` } }] }));
  });
  await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
  t.after(() => { server.closeAllConnections(); server.close(); });
  const addr = server.address(); assert.ok(addr && typeof addr !== "string");
  const baseURL = `http://127.0.0.1:${addr.port}/v1`;
  const cli = path.join(path.dirname(createRequire(import.meta.url).resolve("@codehaus-au/ask/package.json")), "dist/src/cli.js");
  async function ask(...args: string[]) {
    const p = spawn(process.execPath, [cli, "--base-url", baseURL, ...args], { cwd, env, stdio: ["ignore", "pipe", "pipe"] });
    let output = ""; p.stdout.on("data", s => { output += s; }); p.stderr.on("data", s => { output += s; });
    const code = await new Promise(resolve => p.once("close", resolve));
    assert.equal(code, 0, output); return output;
  }
  const open = () => new TuiChat(createClient({ apiKey: "test", baseURL, maxRetries: 0 }), { cwd, env, scope: cwd });
  const chat = open();
  await writeFile(path.join(cwd, "a.ts"), "FIRST_FILE");
  await chat.submit("temporary question");
  await assert.rejects(stat(env.ASK_STATE_DIR), { code: "ENOENT" });
  await ask("--session", "work", "@a.ts cli question");
  await assert.rejects(chat.switchThread("work"), /unused name/);
  assert.equal(chat.lastAnswer, "answer 1");
  await chat.switchThread("docs");
  await chat.switchThread("work");
  assert.equal(chat.threadName, "work"); assert.deepEqual(chat.prompts, ["cli question"]);
  assert.equal(await readCurrentSession(cwd, env), "work");
  await writeFile(path.join(cwd, "a.ts"), "UPDATED_FILE");
  await chat.submit("tui follow-up");
  assert.deepEqual(requests[2]!.messages.filter(m => m.role === "assistant").map(m => m.content), ["answer 2"]);
  assert.match(String(requests[2]!.messages.at(-1)!.content), /UPDATED_FILE/);
  await chat.detach("a.ts");
  await chat.switchThread("docs");
  assert.deepEqual(chat.prompts, ["temporary question"]);
  await ask("--session", "work", "back in cli");
  assert.doesNotMatch(JSON.stringify(requests[3]), /UPDATED_FILE|temporary question/);
  assert.deepEqual(requests[3]!.messages.filter(m => m.role === "assistant").map(m => m.content), ["answer 2", "answer 3"]);
  const restarted = open();
  await restarted.switchThread("work");
  assert.deepEqual(restarted.prompts, ["cli question", "tui follow-up", "back in cli"]);
  const corrupt = sessionPath({ scope: cwd, env, name: "broken" });
  await writeFile(corrupt, "{");
  await assert.rejects(restarted.switchThread("broken"), /invalid or unsupported/);
  assert.equal(await readCurrentSession(cwd, env), "work");
  await ask("--session", "work", "concurrent");
  const conflict = await restarted.submit("unsaved answer");
  assert.match(conflict.saveError!, /changed/);
  assert.equal(restarted.lastAnswer, "answer 6");
  assert.equal((await readThread({ scope: cwd, env, name: "work" })).session!.turns.at(-1)!.question, "concurrent");
  await restarted.switchThread("recovered");
  assert.equal(restarted.prompts.at(-1), "unsaved answer");
  await restarted.newThread();
  assert.deepEqual(restarted.prompts, []);
  const fresh = restarted.threadName;
  assert.ok(fresh);
  assert.equal(await readCurrentSession(cwd, env), fresh);
  assert.ok((await ask("/sessions")).includes(fresh));
  await restarted.switchThread("docs");
  await restarted.clearConversation();
  assert.deepEqual((await readThread({ scope: cwd, name: "docs", env })).session?.turns, []);
  assert.equal(requests.length, 6);
});
